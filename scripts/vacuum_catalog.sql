-- ============================================================================
-- VACUUM CATALOG ITEMS
-- ============================================================================
-- Очистка и оптимизация таблицы catalog_items
-- ВАЖНО: Этот скрипт нужно запускать ОТДЕЛЬНО от миграций!
-- ============================================================================

-- VACUUM не может выполняться в транзакционном блоке, поэтому:
-- 1. Закрой SQL Editor (если открыт)
-- 2. Открой новое окно SQL Editor в Supabase
-- 3. Вставь команду ниже
-- 4. Запусти БЕЗ галочки "Run in transaction" (если есть такая опция)

-- Полная очистка и обновление статистики
VACUUM ANALYZE catalog_items;

-- ============================================================================
-- АЛЬТЕРНАТИВА (если VACUUM не работает):
-- ============================================================================

-- Если VACUUM дает ошибку транзакции, используй только ANALYZE:
-- ANALYZE catalog_items;

-- ============================================================================
-- КОГДА ЗАПУСКАТЬ:
-- ============================================================================

-- 1. После импорта большого количества данных (>1000 записей)
-- 2. После массового удаления записей
-- 3. Раз в неделю для больших баз (>10k записей)
-- 4. Если поиск начал тормозить после добавления данных

-- ============================================================================
-- ПРОВЕРКА РЕЗУЛЬТАТА:
-- ============================================================================

-- После выполнения проверь статистику:
SELECT 
  last_vacuum,
  last_autovacuum,
  last_analyze,
  last_autoanalyze,
  n_tup_ins as inserts,
  n_tup_upd as updates,
  n_tup_del as deletes,
  n_dead_tup as dead_tuples
FROM pg_stat_user_tables 
WHERE relname = 'catalog_items';

-- Если dead_tuples > 0, значит VACUUM нужен
-- Если last_analyze обновилось, значит ANALYZE выполнился успешно
